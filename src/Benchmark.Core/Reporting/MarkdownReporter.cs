using System.Text;

namespace Benchmark.Core;

/// <summary>
/// Renders a <see cref="UseCaseReport"/> to Markdown and writes it to <c>Results/&lt;id&gt;.md</c>.
/// The same renderer is used regardless of which engine produced the report.
/// </summary>
public static class MarkdownReporter
{
    /// <summary>Anything from this marker onward in an existing report is hand-written and preserved
    /// across re-runs (only the generated table above it is overwritten).</summary>
    public const string NotesMarker = "<!-- notes:keep-below — content under this line survives regeneration -->";

    /// <summary>Writes the report to <paramref name="resultsDir"/> and returns the full path. The
    /// generated table is overwritten; any hand-written notes below <see cref="NotesMarker"/> are kept.</summary>
    public static async Task<string> WriteAsync(UseCaseReport report, string resultsDir, CancellationToken ct = default)
    {
        Directory.CreateDirectory(resultsDir);
        var path = Path.Combine(resultsDir, report.Metadata.Id + ".md");
        await File.WriteAllTextAsync(path, Render(report) + await PreservedNotesAsync(path, ct), ct);
        return path;
    }

    private static async Task<string> PreservedNotesAsync(string path, CancellationToken ct)
    {
        string fallback = $"\n---\n\n{NotesMarker}\n\n## Notes\n\n_Hand-written analysis — kept across re-runs. Add yours here._\n";
        if (!File.Exists(path)) return fallback;
        var old = await File.ReadAllTextAsync(path, ct);
        int i = old.IndexOf(NotesMarker, StringComparison.Ordinal);
        return i < 0 ? fallback : "\n---\n\n" + old[i..];
    }

    public static string Render(UseCaseReport report)
    {
        var m  = report.Metadata;
        var e  = report.Environment;
        var sb = new StringBuilder();

        sb.Append("# ").AppendLine(m.Title).AppendLine();
        sb.Append('`').Append(m.Id).Append("` · **").Append(m.Category)
          .Append("** · engine: `").Append(m.Engine).Append('`').AppendLine().AppendLine();
        sb.Append("> ").AppendLine(m.Description).AppendLine();

        sb.AppendLine("| Field | Value |");
        sb.AppendLine("|---|---|");
        sb.Append("| Generated | ").Append(e.TimestampUtc.ToString("u")).AppendLine(" |");
        sb.Append("| Machine | ").Append(e.Machine).AppendLine(" |");
        sb.Append("| OS | ").Append(e.Os).AppendLine(" |");
        sb.Append("| Runtime | ").Append(e.Runtime).AppendLine(" |");
        sb.Append("| CPUs | ").Append(e.ProcessorCount).AppendLine(" |");
        sb.Append("| Samples | ").Append(report.Iterations).Append(" measured")
          .Append(report.Warmup > 0 ? $" (+{report.Warmup} warmup)" : "")
          .AppendLine(", values are medians ± CV% |");
        sb.AppendLine();

        sb.AppendLine("## Results").AppendLine();

        var head = new StringBuilder("| Step |");
        var sep  = new StringBuilder("|---|");
        for (int v = 0; v < report.Variants.Count; v++)
        {
            head.Append(' ').Append(report.Variants[v]).Append(" |");
            sep.Append("---:|");
            if (v > 0) { head.Append(" Δ% |"); sep.Append("---:|"); }
        }
        sb.AppendLine(head.ToString());
        sb.AppendLine(sep.ToString());

        foreach (var row in report.Rows)
        {
            var line = new StringBuilder("| ").Append(row.Step).Append(" |");
            for (int v = 0; v < report.Variants.Count; v++)
            {
                line.Append(' ').Append(ReportFormat.Cell(row.Cells[v])).Append(" |");
                if (v > 0) line.Append(' ').Append(ReportFormat.Gain(row.Cells[v], row.Cells[0])).Append(" |");
            }
            sb.AppendLine(line.ToString());
        }

        sb.AppendLine();
        sb.Append("<sub>Generated by Benchmark.Cli · ").Append(e.TimestampUtc.ToString("u")).AppendLine("</sub>");
        return sb.ToString();
    }
}
