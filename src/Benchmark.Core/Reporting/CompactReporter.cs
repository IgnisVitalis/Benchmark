using System.Text;

namespace Benchmark.Core;

/// <summary>
/// A share-friendly rendering of a <see cref="UseCaseReport"/>: several narrow tables (numbers only,
/// units in the captions) instead of one wide table. Tables are derived from each step's metric, so the
/// layout is identical for every use case and only the tables that apply appear:
/// <list type="bullet">
///   <item><b>Throughput</b> — steps whose unit is a rate (ends in "/sec").</item>
///   <item><b>Time</b> — steps that recorded a wall-clock time (in ms).</item>
///   <item><b>Difference</b> — % vs the baseline variant (+ = better), for the speed steps.</item>
///   <item><b>Size</b> — everything else (e.g. MB), as a per-variant line with a × multiplier.</item>
/// </list>
/// </summary>
public static class CompactReporter
{
    public static async Task<string> WriteAsync(UseCaseReport report, string resultsDir, CancellationToken ct = default)
    {
        Directory.CreateDirectory(resultsDir);
        var path = Path.Combine(resultsDir, report.Metadata.Id + ".compact.md");
        await File.WriteAllTextAsync(path, Render(report), ct);
        return path;
    }

    public static string Render(UseCaseReport report)
    {
        var sb   = new StringBuilder();
        var m    = report.Metadata;
        var e    = report.Environment;
        var vars = report.Variants;

        sb.Append("# ").Append(m.Title).AppendLine(" — compact").AppendLine();
        sb.Append('`').Append(m.Id).Append("` · ").Append(e.Machine).Append(" · ").Append(e.Runtime)
          .Append(" · median of ").Append(report.Iterations).Append(" run(s) · ")
          .Append(e.TimestampUtc.ToString("u")).AppendLine().AppendLine();

        var rate  = report.Rows.Where(MetricGroups.IsRate).ToList();
        var timed = report.Rows.Where(MetricGroups.IsTimed).ToList();
        var speed = report.Rows.Where(r => MetricGroups.IsRate(r) || MetricGroups.IsTimed(r)).ToList();
        var other = report.Rows.Where(MetricGroups.IsOther).ToList();

        if (rate.Count > 0)
        {
            sb.AppendLine("## Throughput — items/sec (higher = faster)").AppendLine();
            Table(sb, vars, rate, c => c is null ? "—" : NumberFormat.Value(c.Median));
        }

        if (timed.Count > 0)
        {
            sb.AppendLine("## Time — ms (lower = faster)").AppendLine();
            Table(sb, vars, timed, c => c?.MedianElapsed is { } el ? NumberFormat.Value(el.TotalMilliseconds) : "—");
        }

        if (speed.Count > 0 && vars.Count > 1)
        {
            sb.AppendLine("## Difference vs baseline — % (+ = faster)").AppendLine();
            DeltaTable(sb, vars, speed);
        }

        if (other.Count > 0)
        {
            sb.AppendLine("## Size").AppendLine();
            foreach (var row in other)
                sb.AppendLine(SizeLine(row, vars));
            sb.AppendLine();
        }

        sb.Append("<sub>Generated by Benchmark.Cli · ").Append(e.TimestampUtc.ToString("u")).AppendLine("</sub>");
        return sb.ToString();
    }

    private static void Table(StringBuilder sb, IReadOnlyList<string> vars, List<StepRow> rows, Func<StepStats?, string> cell)
    {
        Header(sb, vars, fromColumn: 0);
        foreach (var row in rows)
        {
            sb.Append("| ").Append(row.Step).Append(" |");
            foreach (var c in row.Cells) sb.Append(' ').Append(cell(c)).Append(" |");
            sb.AppendLine();
        }
        sb.AppendLine();
    }

    private static void DeltaTable(StringBuilder sb, IReadOnlyList<string> vars, List<StepRow> rows)
    {
        Header(sb, vars, fromColumn: 1);   // baseline (column 0) is the reference, so omit it
        foreach (var row in rows)
        {
            sb.Append("| ").Append(row.Step).Append(" |");
            for (int v = 1; v < vars.Count; v++)
                sb.Append(' ').Append(ReportFormat.Gain(row.Cells[v], row.Cells[0])).Append(" |");
            sb.AppendLine();
        }
        sb.AppendLine();
    }

    private static void Header(StringBuilder sb, IReadOnlyList<string> vars, int fromColumn)
    {
        sb.Append("| Step |");
        for (int v = fromColumn; v < vars.Count; v++) sb.Append(' ').Append(vars[v]).Append(" |");
        sb.AppendLine().Append("|---|");
        for (int v = fromColumn; v < vars.Count; v++) sb.Append("---:|");
        sb.AppendLine();
    }

    private static string SizeLine(StepRow row, IReadOnlyList<string> vars)
    {
        var sb   = new StringBuilder("- **").Append(row.Step).Append(":** ");
        var base_ = row.Cells.Count > 0 ? row.Cells[0] : null;
        for (int v = 0; v < vars.Count; v++)
        {
            if (v > 0) sb.Append(" · ");
            sb.Append(vars[v]).Append(' ');
            var c = row.Cells[v];
            if (c is null) { sb.Append('—'); continue; }
            sb.Append(NumberFormat.Value(c.Median)).Append(' ').Append(c.Unit);
            if (v > 0 && base_ is not null && base_.Median != 0)
                sb.Append(" (").Append(NumberFormat.Value(c.Median / base_.Median)).Append("×)");
        }
        return sb.ToString();
    }
}
